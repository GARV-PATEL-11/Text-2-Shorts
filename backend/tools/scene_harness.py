#!/usr/bin/env python3
"""scene_harness.py — wrap a scene's generated code (scene_code.py) for rendering, one video section per clip.

One file per scene:
  scenes/s03/scene_code.py   the scene-builder's file: class Scene03 with _build_objects, _clip_1, _clip_2, …, construct
  scenes/s03/scene.py        GENERATED here — never edited by an LLM

The wrapper subclasses the generated class: it draws the template's backdrop, border and fonts first, then opens a
Manim section clip_NN before each _clip_N method, so every clip renders to its own video (muxed with its own
narration) while the scene runs as one piece of code.

Rendering uses Manim sections (verified on 0.20.1):
  * every clip opens a section → `--save_sections` emits one MP4 per clip + a JSON with durations;
  * `--target clip_02` marks earlier sections skip_animations=True: their code still runs (exact entry
    state, no reconstruction) but no frames are rendered, so a single-clip draft is fast;
  * clips after the target are not executed at all (TEXT_2_SHORTS_STOP_AFTER).

Usage:
  python backend/tools/scene_harness.py compose scenes/s03 --scene-id s03
  python backend/tools/scene_harness.py render  scenes/s03 --scene-id s03 [--target clip_02] [--quality l|m|h|k]
"""

from __future__ import annotations

import argparse
import ast
import json
import os
import subprocess
import sys
from pathlib import Path

TEMPLATE = '''# GENERATED by backend/tools/scene_harness.py — do not edit. The scene's code is scene_code.py.
import json
import os
import re
import sys
from manim import *

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from scene_code import {cls} as _Generated  # noqa: E402

_LOOK = json.loads(os.environ.get("TEXT_2_SHORTS_LOOK") or "null")  # the template's drawing (video_settings.drawing)
if _LOOK:
    sys.path.insert(0, {runtime!r})
    import look_renderer
    look_renderer.register_fonts()
_TARGET = os.environ.get("TEXT_2_SHORTS_TARGET_CLIP")      # render only this clip's frames
_STOP_AFTER = os.environ.get("TEXT_2_SHORTS_STOP_AFTER")   # do not execute clips after this one


def _as_section(method_name, method):
    section = "clip_" + method_name.rsplit("_", 1)[1].zfill(2)

    def run(self, *args, **kwargs):
        if _STOP_AFTER and section > _STOP_AFTER:
            return None
        self._clip = section
        self.next_section(section, skip_animations=bool(_TARGET) and section < _TARGET)
        return method(self, *args, **kwargs)

    return run


class {cls}(_Generated):
    def construct(self):
        self.beat_log = []                                  # [clip, beat number, scene time] per self.beat(n)
        self._backdrop = []                                 # the template's backdrop and border, behind every clip
        if _LOOK:
            self.camera.background_color = look_renderer.background_colour(_LOOK)
            self._backdrop = look_renderer.backdrop(_LOOK) + [b for b in [look_renderer.border(_LOOK)] if b is not None]
            self.add(*self._backdrop)
        super().construct()

    def content(self):
        """What the scene puts on screen (never the template's backdrop or border)."""
        return [mobject for mobject in self.mobjects if mobject not in self._backdrop]

    def beat(self, number):
        """Optional: mark where beat <number> of the current clip starts, for the sync report."""
        self.beat_log.append([self._clip, number, round(float(self.renderer.time), 3)])


for _name in [name for name in dir(_Generated) if re.fullmatch(r"_clip_\\d+", name)]:
    setattr({cls}, _name, _as_section(_name, getattr(_Generated, _name)))
'''


RUNTIME_TEMPLATE = Path(  # look_renderer.py, copied there with the chosen template (backend/app/workflow/templates.py)
    os.environ.get("TEXT_2_SHORTS_RUNTIME_TEMPLATE")
    or Path(__file__).resolve().parents[2] / "runtime-environment" / "template"
)


def class_name(scene_id: str) -> str:
    return "Scene" + scene_id[1:].zfill(2)


def compose_scene(scene_dir: Path, scene_id: str) -> Path:
    """scene.py beside scene_code.py: the generated class, wrapped with the template and one section per clip."""
    code = scene_dir / "scene_code.py"
    if not code.exists():
        raise SystemExit(f"no scene_code.py in {scene_dir}")
    tree = ast.parse(code.read_text())
    cls = class_name(scene_id)
    if not any(isinstance(node, ast.ClassDef) and node.name == cls for node in tree.body):
        raise SystemExit(f"{code}: must define class {cls}")
    scene_path = scene_dir / "scene.py"
    scene_path.write_text(TEMPLATE.format(cls=cls, runtime=str(RUNTIME_TEMPLATE)))
    return scene_path


# Quality presets (-ql/-qm/-qh) OVERRIDE pixel_width/height from manim.cfg (verified on 0.20.1: a 1080x1920
# manim.cfg rendered with -ql gives 854x480). Portrait output therefore always passes -r explicitly.
PORTRAIT_RESOLUTIONS = {"l": "480,854", "m": "720,1280", "h": "1080,1920", "k": "2160,3840"}


def render_scene(
    scene_dir: Path,
    scene_id: str,
    target: str | None,
    quality: str,
    media: str = "media",
    aspect: str = "16:9",
    fps: int | None = None,
) -> dict:
    env = dict(os.environ)
    if target:
        env["TEXT_2_SHORTS_TARGET_CLIP"] = target
        env["TEXT_2_SHORTS_STOP_AFTER"] = target
    scene_class = class_name(scene_id)
    command = [
        sys.executable,
        "-m",
        "manim",
        "render",
        "scene.py",
        scene_class,
        f"-q{quality}",
        "--save_sections",
        "--media_dir",
        media,
        "--disable_caching",
    ]
    if aspect == "9:16":
        command += ["-r", PORTRAIT_RESOLUTIONS[quality]]
    if fps:
        command += ["--fps", str(fps)]
    process = subprocess.run(command, cwd=scene_dir, env=env, capture_output=True, text=True, timeout=3600)
    if process.returncode != 0:
        return {"ok": False, "returncode": process.returncode, "stderr_tail": process.stderr[-3000:]}
    sections_json = next((scene_dir / media).rglob(f"sections/{scene_class}.json"))
    sections = json.loads(sections_json.read_text())
    for section in sections:
        section["path"] = str((sections_json.parent / section["video"]).relative_to(scene_dir))
        section["duration"] = float(section["duration"])
    return {"ok": True, "class": scene_class, "target": target, "quality": quality, "sections": sections}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("action", choices=["compose", "render"])
    parser.add_argument("scene_dir", type=Path)
    parser.add_argument("--scene-id", required=True)
    parser.add_argument("--target")
    parser.add_argument("--quality", default="l", choices=list("lmhpk"))
    parser.add_argument("--fps", type=int)
    parser.add_argument("--media", default="media")
    parser.add_argument("--aspect", default="16:9", choices=["16:9", "9:16"])
    arguments = parser.parse_args()
    if arguments.action == "compose":
        print(compose_scene(arguments.scene_dir, arguments.scene_id))
    else:
        result = render_scene(
            arguments.scene_dir,
            arguments.scene_id,
            arguments.target,
            arguments.quality,
            media=arguments.media,
            aspect=arguments.aspect,
            fps=arguments.fps,
        )
        print(json.dumps(result, indent=1))
        sys.exit(0 if result["ok"] else 1)


if __name__ == "__main__":
    main()
