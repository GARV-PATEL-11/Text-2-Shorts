#!/usr/bin/env python3
"""scene_harness.py — compose a scene from isolated clip files and render clip-level outputs.

Clip isolation by construction:
  scenes/s03/clips/clip_01.py   defines exactly `def clip_01(self): ...`
  scenes/s03/clips/clip_02.py   defines exactly `def clip_02(self): ...`
  scenes/s03/scene.py           GENERATED here — never edited by an LLM

The clip agent for s03c02 may only write clips/clip_02.py, so it cannot break clip_01 or clip_03.
Continuity objects are passed through `self.reg` (names = continuity contract).

Rendering uses Manim sections (verified on 0.20.1):
  * every clip opens a section → `--save_sections` emits one MP4 per clip + a JSON with durations;
  * `--target clip_02` marks earlier sections skip_animations=True: their code still runs (exact entry
    state, no reconstruction) but no frames are rendered, so a single-clip draft is fast;
  * clips after the target are not executed at all (TEXT_2_SHORTS_STOP_AFTER).

Usage:
  python tools/scene_harness.py compose scenes/s03 --scene-id s03 [--camera]
  python tools/scene_harness.py render  scenes/s03 --scene-id s03 [--target clip_02] [--quality l|m|h|k]
Status: IMPLEMENTED in this package (tests/test_scene_harness.py).
"""

from __future__ import annotations
import argparse
import ast
import json
import os
import subprocess
import sys
from pathlib import Path

TEMPLATE = '''# GENERATED by tools/scene_harness.py — do not edit. Edit clips/clip_NN.py instead.
import os
from manim import *
{imports}

_TARGET = os.environ.get("TEXT_2_SHORTS_TARGET_CLIP")      # render only this clip's frames
_STOP_AFTER = os.environ.get("TEXT_2_SHORTS_STOP_AFTER")   # do not execute clips after this one


class {cls}({base}):
    CLIPS = {clips!r}

    def construct(self):
        self.reg = {{}}
        if os.environ.get("TEXT_2_SHORTS_BACKGROUND"):        # one background for every clip and scene of a video
            self.camera.background_color = os.environ["TEXT_2_SHORTS_BACKGROUND"]
        for name in self.CLIPS:
            self.next_section(name, skip_animations=bool(_TARGET) and name < _TARGET)
            getattr(self, name)()
            if _STOP_AFTER and name >= _STOP_AFTER:
                break
{binds}
'''


def class_name(scene_id: str) -> str:
    return "Scene" + scene_id[1:].zfill(2)


def check_clip_file(path: Path) -> str:
    """A clip file may contain only imports, module constants and exactly one function named like the file."""
    tree = ast.parse(path.read_text())
    functions = [node for node in tree.body if isinstance(node, ast.FunctionDef)]
    if len(functions) != 1 or functions[0].name != path.stem:
        raise SystemExit(f"{path}: must define exactly one function named {path.stem}")
    for node in tree.body:
        if not isinstance(node, (ast.FunctionDef, ast.Import, ast.ImportFrom, ast.Assign, ast.Expr)):
            raise SystemExit(f"{path}: unexpected top-level statement {type(node).__name__}")
    return path.stem


def compose_scene(scene_dir: Path, scene_id: str, camera: bool = False) -> Path:
    clips = sorted(scene_dir.glob("clips/clip_*.py"))
    if not clips:
        raise SystemExit(f"no clips in {scene_dir}/clips")
    names = [check_clip_file(clip_path) for clip_path in clips]
    imports = "\n".join(f"from clips.{name} import {name} as _{name}" for name in names)
    binds = "\n".join(f"    {name} = _{name}" for name in names)
    source = TEMPLATE.format(
        imports=imports,
        cls=class_name(scene_id),
        base="MovingCameraScene" if camera else "Scene",
        clips=names,
        binds=binds,
    )
    (scene_dir / "clips" / "__init__.py").write_text("")
    scene_path = scene_dir / "scene.py"
    scene_path.write_text(source)
    return scene_path


# Quality presets (-ql/-qm/-qh) OVERRIDE pixel_width/height from manim.cfg (verified on 0.20.1: a 1080x1920
# manim.cfg rendered with -ql gives 854x480). Portrait output therefore always passes -r explicitly.
PORTRAIT_RESOLUTIONS = {"l": "480,854", "m": "720,1280", "h": "1080,1920", "k": "2160,3840"}


def render_scene(
    scene_dir: Path,
    scene_id: str,
    target: str | None,
    quality: str,
    media: str = "media",
    aspect: str = "16:9",
    fps: int | None = None,
) -> dict:
    env = dict(os.environ)
    if target:
        env["TEXT_2_SHORTS_TARGET_CLIP"] = target
        env["TEXT_2_SHORTS_STOP_AFTER"] = target
    scene_class = class_name(scene_id)
    command = [
        sys.executable,
        "-m",
        "manim",
        "render",
        "scene.py",
        scene_class,
        f"-q{quality}",
        "--save_sections",
        "--media_dir",
        media,
        "--disable_caching",
    ]
    if aspect == "9:16":
        command += ["-r", PORTRAIT_RESOLUTIONS[quality]]
    if fps:
        command += ["--fps", str(fps)]
    process = subprocess.run(command, cwd=scene_dir, env=env, capture_output=True, text=True, timeout=3600)
    if process.returncode != 0:
        return {"ok": False, "returncode": process.returncode, "stderr_tail": process.stderr[-3000:]}
    sections_json = next((scene_dir / media).rglob(f"sections/{scene_class}.json"))
    sections = json.loads(sections_json.read_text())
    for section in sections:
        section["path"] = str((sections_json.parent / section["video"]).relative_to(scene_dir))
        section["duration"] = float(section["duration"])
    return {"ok": True, "class": scene_class, "target": target, "quality": quality, "sections": sections}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("action", choices=["compose", "render"])
    parser.add_argument("scene_dir", type=Path)
    parser.add_argument("--scene-id", required=True)
    parser.add_argument("--camera", action="store_true")
    parser.add_argument("--target")
    parser.add_argument("--quality", default="l", choices=list("lmhpk"))
    parser.add_argument("--fps", type=int)
    parser.add_argument("--media", default="media")
    parser.add_argument("--aspect", default="16:9", choices=["16:9", "9:16"])
    arguments = parser.parse_args()
    if arguments.action == "compose":
        print(compose_scene(arguments.scene_dir, arguments.scene_id, arguments.camera))
    else:
        result = render_scene(
            arguments.scene_dir,
            arguments.scene_id,
            arguments.target,
            arguments.quality,
            media=arguments.media,
            aspect=arguments.aspect,
            fps=arguments.fps,
        )
        print(json.dumps(result, indent=1))
        sys.exit(0 if result["ok"] else 1)


if __name__ == "__main__":
    main()
